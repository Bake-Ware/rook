#!/usr/bin/env python3
"""Check that the user manual (docs/manual) covers every current feature.

    python tools/manual_check.py --pages         # pages parse and their links resolve (pytest runs this)
    python tools/manual_check.py                 # also coverage and the CHANGELOG (CI, advisory)
    python tools/manual_check.py --base master   # also: pages the CHANGELOG names changed since master
    python tools/manual_check.py --release v0.2.0   # the release gate (tools/release_prep.py)
    python tools/manual_check.py --write         # write docs/manual/manifest.json (built, not committed)
    python tools/manual_check.py --list          # print the feature inventory and its pages

Only ``--release`` blocks anything: pull requests that don't touch the
manual are never failed by coverage or CHANGELOG findings (CI shows them in
a job that may fail), but a release can't be cut with a stale manual.

A *feature* is any of:

* a ``##``/``###`` heading of docs/FEATURES.md   -> ``features/<heading-slug>``
* a settings group of the hub's settings schema  -> ``settings/core/<group>`` and
  ``settings/<plugin or service namespace>``
* a hub or worker plugin module                  -> ``plugin/hub/<module>``, ``plugin/worker/<module>``
* a ``rook`` command and ``rook hub`` subcommand  -> ``cli/<command>``, ``cli/hub/<sub>``

Problems:

1. (``--pages``) a page does not parse (front matter: id, title, features,
   since, deprecated, optional preview) or links to a manual page that does
   not exist (``[[manual-<id>]]``);
2. a feature has no page covering it (a deprecated page counts: the feature
   still exists, the page says it is going away);
3. a page covers a feature that no longer exists and is not marked
   ``deprecated: true`` (removed features keep a deprecated page, or lose the
   mapping);
4. a bullet under an ``Added``, ``Removed`` or ``Deprecated`` heading
   (``###`` or ``####``) in the CHANGELOG's *Unreleased* section names no
   manual pages: ``(manual: <page-id>, ...)`` on the bullet or a line
   ``Manual: <page-id>, ...`` in its block; ``n/a`` says it is not
   user-visible;
5. with ``--base REF`` (implied by ``--release``, against the previous tag):
   a page named that way did not change since REF (with ``--base`` alone,
   pages REF's CHANGELOG already named are left out: they belong to changes
   already merged); with ``--release``, a page's ``since`` is newer than the
   release.

docs/manual/manifest.json (pages in order with content hashes, and the
feature-to-page map) is generated by ``--write`` and by tools/release_prep.py
when a release is built, so it never conflicts between pull requests.

Stdlib only, offline (``--base`` runs ``git``).
"""
from __future__ import annotations

import argparse
import importlib
import inspect
import pkgutil
import re
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
if str(ROOT) not in sys.path:
    sys.path.insert(0, str(ROOT))

from rook.hub.plugins.manual import bundle as manual_bundle  # noqa: E402

MANUAL_DIR = ROOT / "docs" / "manual"
FEATURES_MD = ROOT / "docs" / "FEATURES.md"
CHANGELOG = ROOT / "CHANGELOG.md"

FEATURE_HEADINGS = ("added", "removed", "deprecated")
BULLET_MARK = re.compile(r"[\(\[]\s*manual\s*:\s*([^\)\]]*)[\)\]]", re.I)
BLOCK_MARK = re.compile(r"^Manual\s*:\s*(.+)$", re.I)
NOT_APPLICABLE = {"n/a", "na", "none"}
LINK = re.compile(r"\[\[([a-z0-9][a-z0-9-]{0,79})\]\]")


def slug(text: str) -> str:
    return re.sub(r"[^a-z0-9]+", "-", text.lower()).strip("-")


# -- the feature inventory ------------------------------------------------------

def features_md(path: Path = FEATURES_MD) -> dict:
    out = {}
    in_code = False
    for line in path.read_text(encoding="utf-8").splitlines():
        if line.startswith("```"):
            in_code = not in_code
        m = None if in_code else re.match(r"^(##|###)\s+(.+?)\s*$", line)
        if m:
            out["features/" + slug(m.group(2).replace("`", ""))] = f"docs/FEATURES.md: {m.group(2)}"
    return out


def settings_features() -> dict:
    from rook.hub.settings_schema import Schema
    schema = Schema()
    if schema.import_errors:
        raise RuntimeError("plugin modules failed to import, the settings inventory would be "
                           "incomplete: " + "; ".join(schema.import_errors))
    out = {}
    for e in schema:
        if e.origin == "core":
            out[f"settings/core/{slug(e.setting.group or 'general')}"] = \
                f"settings group {e.setting.group or 'General'} (core)"
        else:
            out[f"settings/{e.namespace}"] = f"settings of {e.namespace} ({e.origin})"
    return out


def plugin_features() -> dict:
    from rook.core.plugin import Plugin
    out = {}
    for side in ("hub", "worker"):
        pkg = importlib.import_module(f"rook.{side}.plugins")
        for info in pkgutil.iter_modules(pkg.__path__):
            if info.name.startswith("_"):
                continue
            mod = importlib.import_module(f"rook.{side}.plugins.{info.name}")
            classes = [o for _, o in inspect.getmembers(mod, inspect.isclass)
                       if issubclass(o, Plugin) and o is not Plugin and o.NAMESPACE
                       and o.__module__.startswith(mod.__name__)]
            if classes or getattr(mod, "PLUGIN", None) is not None:
                ns = classes[0].NAMESPACE if classes else ""
                out[f"plugin/{side}/{info.name}"] = f"{side} plugin {info.name} ({ns})"
    return out


def cli_features() -> dict:
    import argparse as _ap
    from rook.__main__ import SUBCOMMANDS
    from rook.hubdeploy.cli import build_parser
    out = {f"cli/{c}": f"rook {c}" for c in SUBCOMMANDS}
    for action in build_parser()._actions:
        if isinstance(action, _ap._SubParsersAction):
            for sub in action.choices:
                out[f"cli/hub/{sub}"] = f"rook hub {sub}"
    return out


def inventory() -> dict:
    """``{feature id: where it comes from}``."""
    out = {}
    for part in (features_md(), settings_features(), plugin_features(), cli_features()):
        out.update(part)
    return out


# -- CHANGELOG ------------------------------------------------------------------

def changelog_section(text: str, version: str | None = None) -> list[str]:
    """Lines of the ``## Unreleased`` section (or of ``## <version>`` /
    ``## [<version>]`` when given and present)."""
    lines = text.splitlines()
    wanted = [r"unreleased"]
    if version:
        wanted.insert(0, r"\[?v?" + re.escape(version) + r"\]?")
    for pattern in wanted:
        for i, line in enumerate(lines):
            if re.match(r"^##\s+" + pattern + r"\b", line, re.I):
                j = i + 1
                while j < len(lines) and not re.match(r"^##\s", lines[j]):
                    j += 1
                return lines[i + 1:j]
    return []


def _refs(raw: str) -> list[str]:
    return [r.strip().lower() for r in re.split(r"[,\s]+", raw.strip()) if r.strip()]


def changelog_bullets(section: list[str]) -> list[dict]:
    """Bullets with their ``###`` block, its ``Manual:`` refs and their own."""
    blocks: list[dict] = []
    block = {"heading": "", "refs": None, "bullets": []}
    blocks.append(block)
    bullet = None
    for line in section:
        if re.match(r"^####?\s", line):
            block = {"heading": line.lstrip("#").strip(), "refs": None, "bullets": []}
            blocks.append(block)
            bullet = None
            continue
        mark = BLOCK_MARK.match(line)
        if mark:
            block["refs"] = _refs(mark.group(1))
            bullet = None
            continue
        if line.startswith("- "):
            bullet = {"text": line[2:]}
            block["bullets"].append(bullet)
        elif bullet is not None and line.startswith("  ") and line.strip():
            bullet["text"] += " " + line.strip()
        elif not line.strip():
            bullet = None
    out = []
    for b in blocks:
        for item in b["bullets"]:
            own = BULLET_MARK.search(item["text"])
            out.append({"heading": b["heading"], "text": item["text"],
                        "refs": _refs(own.group(1)) if own else b["refs"],
                        "feature": b["heading"].strip().lower() in FEATURE_HEADINGS})
    return out


def check_changelog(text: str, page_ids: set, version: str | None = None) -> tuple[list, set]:
    """(problems, page ids the section names)."""
    problems, named = [], set()
    for b in changelog_bullets(changelog_section(text, version)):
        if not b["feature"]:
            continue
        first = b["text"][:90] + ("…" if len(b["text"]) > 90 else "")
        where = f"CHANGELOG ({b['heading'] or 'Unreleased'}): {first!r}"
        if not b["refs"]:
            problems.append(f"{where} adds or removes a feature but names no manual page: "
                            f"add (manual: <page-id>) to the bullet or a 'Manual: <page-id>' line "
                            f"to its block ('n/a' if it is not user-visible)")
            continue
        for ref in b["refs"]:
            if ref in NOT_APPLICABLE:
                continue
            pid = ref[len(manual_bundle.SLUG_PREFIX):] if ref.startswith(manual_bundle.SLUG_PREFIX) else ref
            if pid not in page_ids:
                problems.append(f"{where} names manual page {ref!r}, which does not exist")
            else:
                named.add(pid)
    return problems, named


# -- git ------------------------------------------------------------------------

def changed_pages(base: str, root: Path = ROOT) -> set:
    """Page ids whose file differs between ``base`` and the working tree."""
    try:
        out = subprocess.run(["git", "diff", "--name-only", base, "--", "docs/manual"],
                             cwd=root, capture_output=True, text=True, check=True).stdout
        # New pages not added to git yet are changes too.
        out += subprocess.run(["git", "ls-files", "--others", "--exclude-standard", "--", "docs/manual"],
                              cwd=root, capture_output=True, text=True, check=True).stdout
    except (OSError, subprocess.CalledProcessError) as e:
        raise RuntimeError(f"git diff against {base!r} failed: {e}") from e
    return {Path(p).stem for p in out.split() if p.endswith(".md")}


def changelog_named_at(base: str, page_ids: set, root: Path = ROOT) -> set:
    """Page ids the *Unreleased* section of ``base``'s CHANGELOG already
    names (empty when ``base`` has no CHANGELOG)."""
    try:
        out = subprocess.run(["git", "show", f"{base}:CHANGELOG.md"], cwd=root,
                             capture_output=True, text=True)
    except OSError:
        return set()
    return check_changelog(out.stdout, page_ids)[1] if out.returncode == 0 else set()


def previous_tag(root: Path = ROOT) -> str | None:
    try:
        out = subprocess.run(["git", "describe", "--tags", "--abbrev=0", "HEAD^"], cwd=root,
                             capture_output=True, text=True)
    except OSError:
        return None
    return out.stdout.strip() or None if out.returncode == 0 else None


def _vtuple(v: str) -> tuple:
    return tuple(int(x) for x in re.findall(r"\d+", v.split("+")[0])[:3])


# -- the check ------------------------------------------------------------------

def check(directory: Path = MANUAL_DIR, *, features: dict | None = None,
          changelog: str | None = None, base: str | None = None,
          release: str | None = None, root: Path = ROOT, pages_only: bool = False) -> list[str]:
    """Every problem found, as one line each (empty: the manual is current).
    ``pages_only``: parsing and links only (what pytest checks)."""
    b = manual_bundle.load(directory)
    problems = list(b.errors)
    if not b.pages:
        return problems or ["the manual has no pages"]
    page_ids = {p.id for p in b.pages}

    # 1. links
    for p in b.pages:
        prose = re.sub(r"`[^`\n]*`", "", re.sub(r"(?ms)^```.*?^```", "", p.body))
        for target in LINK.findall(prose):
            if target == manual_bundle.ROOT_SLUG:
                continue
            if not target.startswith(manual_bundle.SLUG_PREFIX):
                problems.append(f"{p.file}: [[{target}]] is not a manual page link "
                                f"(write [[{manual_bundle.SLUG_PREFIX}<id>]])")
            elif target[len(manual_bundle.SLUG_PREFIX):] not in page_ids:
                problems.append(f"{p.file}: [[{target}]] links to a page that does not exist")

    if pages_only:
        return problems

    # 3, 4. coverage both ways
    features = inventory() if features is None else features
    live: dict = {}
    for p in b.pages:
        for f in p.features:
            live.setdefault(f, []).append(p)
    for fid, origin in sorted(features.items()):
        if not live.get(fid):
            problems.append(f"{fid} ({origin}) has no manual page: add it to a page's features "
                            f"(docs/manual/<page>.md) and describe it there")
    for fid, pages in sorted(live.items()):
        if fid not in features:
            stale = [p.file for p in pages if not p.deprecated]
            if stale:
                problems.append(f"{fid} (on {', '.join(stale)}) is not a current feature: if it was "
                                f"removed, mark the page deprecated or drop the mapping")

    # 5. CHANGELOG
    version = release.lstrip("v") if release else None
    text = changelog if changelog is not None else (root / "CHANGELOG.md").read_text(encoding="utf-8")
    cl_problems, named = check_changelog(text, page_ids, version)
    problems += cl_problems

    # 6. against a base revision / for a release
    if release and base is None:
        base = previous_tag(root)
    if base:
        changed = changed_pages(base, root)
        # For a branch (not the release gate), pages the CHANGELOG already
        # named at ``base`` were that change's to update, not this one's.
        already = set() if release else changelog_named_at(base, page_ids, root)
        for pid in sorted(named - changed - already):
            problems.append(f"CHANGELOG names manual page {pid!r}, but docs/manual/{pid}.md did not "
                            f"change since {base}")
    if version:
        for p in b.pages:
            if _vtuple(p.since) > _vtuple(version):
                problems.append(f"{p.file}: since {p.since} is newer than the release {version}")
    return problems


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--write", action="store_true", help="write docs/manual/manifest.json first")
    ap.add_argument("--pages", action="store_true", help="only check that pages parse and links resolve")
    ap.add_argument("--base", help="git revision: CHANGELOG-named pages must have changed since it")
    ap.add_argument("--release", help="release tag (v1.2.3): the release gate; base = previous tag")
    ap.add_argument("--list", action="store_true", help="print the feature inventory and its pages")
    ap.add_argument("--dir", type=Path, default=MANUAL_DIR, help=argparse.SUPPRESS)
    args = ap.parse_args(argv)
    if args.write:
        b = manual_bundle.load(args.dir)
        if b.errors:
            print("\n".join(b.errors), file=sys.stderr)
            return 1
        print(f"wrote {manual_bundle.write_manifest(b)}")
    if args.list:
        b = manual_bundle.load(args.dir)
        pages = {}
        for p in b.pages:
            for f in p.features:
                pages.setdefault(f, []).append(p.id)
        for fid, origin in sorted(inventory().items()):
            print(f"{fid:48s} {', '.join(pages.get(fid, [])) or '-- MISSING --':30s} {origin}")
        return 0
    problems = check(args.dir, base=args.base, release=args.release, pages_only=args.pages)
    if problems:
        print(f"The user manual is out of date ({len(problems)} problem"
              f"{'s' if len(problems) != 1 else ''}):", file=sys.stderr)
        for p in problems:
            print("  - " + p, file=sys.stderr)
        print("See CONTRIBUTING.md, 'The user manual'.", file=sys.stderr)
        return 1
    b = manual_bundle.load(args.dir)
    if args.pages:
        print(f"manual pages ok: {len(b.pages)} pages")
    else:
        print(f"manual ok: {len(b.pages)} pages cover {len(inventory())} features")
    return 0


if __name__ == "__main__":
    sys.exit(main())
