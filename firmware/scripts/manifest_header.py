"""Write include/manifest.h: the plugin, version and the two hashes the
dongle announces (docs/spec/worker-profile.md section 2), computed from
rook/plugins/dongle-s3/plugin.yaml. PlatformIO runs it before every build
(extra_scripts in platformio.ini); by hand:

    python3 firmware/scripts/manifest_header.py rook/plugins/dongle-s3/plugin.yaml out.h

The manifest is written as JSON (YAML's JSON subset) after its comment lines,
so the standard library reads it."""

import hashlib
import json
import sys
from pathlib import Path


def canonical(value) -> bytes:
    """RFC 8785 for objects, lists, strings, integers and booleans: sorted keys, no spaces."""
    return json.dumps(value, sort_keys=True, separators=(",", ":"), ensure_ascii=False).encode()


def header(text: str) -> str:
    manifest = json.loads("".join(line for line in text.splitlines(True) if not line.lstrip().startswith("#")))
    entries = [{"plugin": manifest["plugin"], "version": manifest["version"],
                "hash": hashlib.sha256(canonical(manifest)).hexdigest()}]
    return ("// Generated by scripts/manifest_header.py from the dongle's plugin.yaml; do not edit.\n"
            "#pragma once\n"
            f"#define ROOK_MANIFEST_PLUGIN {json.dumps(entries[0]['plugin'])}\n"
            f"#define ROOK_MANIFEST_VERSION {json.dumps(entries[0]['version'])}\n"
            f"#define ROOK_MANIFEST_HASH \"{entries[0]['hash']}\"\n"
            f"#define ROOK_MANIFESTS_HASH \"{hashlib.sha256(canonical(entries)).hexdigest()}\"\n")


def write(manifest: Path, out: Path) -> None:
    text = header(manifest.read_text(encoding="utf-8"))
    if not out.exists() or out.read_text() != text:
        out.write_text(text)


if __name__ == "__main__":
    write(Path(sys.argv[1]), Path(sys.argv[2]))
else:
    Import("env")  # noqa: F821  (PlatformIO's SCons)
    project = Path(env["PROJECT_DIR"])  # noqa: F821
    write(project.parent / "rook" / "plugins" / "dongle-s3" / "plugin.yaml", project / "include" / "manifest.h")
