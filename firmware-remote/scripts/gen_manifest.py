#!/usr/bin/env python3
"""Validate manifest/remote.yaml and write include/remote_manifest.h.

    python3 firmware-remote/scripts/gen_manifest.py

The header holds the manifest as canonical JSON (spec core-v2 3.2): the
firmware serves exactly these bytes' object from core.manifests and announces
SHA-256 of them as the manifest hash, which is what the hub computes over the
parsed manifest. Re-run after every edit to the YAML and commit both files.
Validation uses rook.kit.manifest from this checkout when it imports.
"""
import hashlib
import json
import math
import sys
from pathlib import Path

import yaml

HERE = Path(__file__).resolve().parents[1]
REPO = HERE.parent
SRC = HERE / "manifest" / "remote.yaml"
OUT = HERE / "include" / "remote_manifest.h"


def _number(x):
    if isinstance(x, int):
        return str(x)
    if not math.isfinite(x):
        raise ValueError("no JSON form")
    if x == int(x):
        return str(int(x))
    return repr(x)


def canon(v):
    if v is None:
        return "null"
    if v is True:
        return "true"
    if v is False:
        return "false"
    if isinstance(v, (int, float)):
        return _number(v)
    if isinstance(v, str):
        return json.dumps(v, ensure_ascii=False)
    if isinstance(v, list):
        return "[" + ",".join(canon(x) for x in v) + "]"
    if isinstance(v, dict):
        keys = sorted(v, key=lambda k: k.encode("utf-16-be"))
        return "{" + ",".join(json.dumps(k, ensure_ascii=False) + ":" + canon(v[k]) for k in keys) + "}"
    raise ValueError(f"not JSON: {type(v).__name__}")


def validate(data):
    sys.path.insert(0, str(REPO))
    try:
        from rook.core2 import wire
        from rook.kit.manifest import validate as kit_validate   # noqa: F401
    except Exception as e:  # pragma: no cover - depends on the checkout's deps
        print(f"note: rook.kit not importable here ({e}); skipped schema validation")
        return None
    issues = kit_validate(data)
    errors = [i for i in issues if getattr(i, "level", "error") == "error"]
    for i in issues:
        print(f"{getattr(i, 'level', '?')}: {i}")
    if errors:
        sys.exit("manifest has errors")
    return wire.manifest_hash(data)


def main():
    data = yaml.safe_load(SRC.read_text(encoding="utf-8"))
    text = canon(data)
    digest = hashlib.sha256(text.encode("utf-8")).hexdigest()
    ref = validate(data)
    if ref is not None and ref != digest:
        sys.exit(f"hash mismatch with rook.core2.wire: {ref} != {digest}")
    OUT.parent.mkdir(exist_ok=True)
    c = json.dumps(text)          # a C string literal is a JSON string for this ASCII text
    if not text.isascii():
        sys.exit("keep the manifest ASCII so the C literal stays exact")
    OUT.write_text(
        "// Generated by scripts/gen_manifest.py from manifest/remote.yaml. Do not edit.\n"
        "#pragma once\n"
        f"#define REMOTE_MANIFEST_VERSION \"{data['version']}\"\n"
        f"#define REMOTE_MANIFEST_HASH \"{digest}\"\n"
        f"static const char REMOTE_MANIFEST_JSON[] = {c};\n", encoding="utf-8")
    print(f"{OUT.relative_to(REPO)}: {len(text)} bytes, sha256 {digest}")


if __name__ == "__main__":
    main()
