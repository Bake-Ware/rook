#!/usr/bin/env bash
# Generate src/disk_image.h — a small read-only FAT12 image holding the host
# client files, embedded into the firmware and served over USB MSC. Re-run this
# whenever the client files change, then rebuild + reflash.
set -euo pipefail
HERE="$(cd "$(dirname "$0")/.." && pwd)"
CLIENT="$HERE/../client"
OUT="$HERE/src/disk_image.h"
IMG="$(mktemp --suffix=.img)"
trap 'rm -f "$IMG"' EXIT

SIZE_KB=256
truncate -s "${SIZE_KB}K" "$IMG"
mkfs.fat -F 12 -n ROOK "$IMG" >/dev/null

# A short pointer file so whoever plugs it in knows what to do.
READ_ME="$(mktemp)"
cat > "$READ_ME" <<'TXT'
Rook HID-KVM bridge — host client
=================================
This Pico bridges keyboard + trackball from this PC to another machine.

Run (needs root for /dev/input and the serial port):
    sudo python3 rook_hid_pico.py        # auto-detects the bridge port
Deps: pip install evdev pyserial

Double-tap RIGHT CTRL to start/stop driving the other machine.
Full notes in the docstring at the top of rook_hid_pico.py.
TXT

mcopy -i "$IMG" "$CLIENT/rook_hid_pico.py" ::/rook_hid_pico.py
mcopy -i "$IMG" "$CLIENT/run_pico.sh"      ::/run_pico.sh
mcopy -i "$IMG" "$READ_ME"                 ::/README.txt
rm -f "$READ_ME"

{
    echo "// Auto-generated by tools/mkdisk.sh — DO NOT EDIT."
    echo "// Read-only FAT12 image (${SIZE_KB}K) of the host client files, served over USB MSC."
    echo "#pragma once"
    echo "const unsigned char rook_disk[] = {"
    xxd -i < "$IMG"
    echo "};"
    echo "const unsigned long rook_disk_len = sizeof(rook_disk);"
} > "$OUT"

echo "wrote $OUT ($(wc -c < "$OUT") bytes, image ${SIZE_KB}K = $((SIZE_KB*1024/512)) blocks)"
